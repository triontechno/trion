#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
command -v git >/dev/null
command -v rsync >/dev/null

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
LOCK="$TMP/UPSTREAMS.lock"
printf '# Generated by scripts/import-core-sources.sh\n# name\turl\tcommit\n' > "$LOCK"

components=(
  "kernel|https://gitlab.redox-os.org/redox-os/kernel.git"
  "base|https://gitlab.redox-os.org/redox-os/base.git"
  "redoxfs|https://gitlab.redox-os.org/redox-os/redoxfs.git"
  "relibc|https://gitlab.redox-os.org/redox-os/relibc.git"
  "ion|https://gitlab.redox-os.org/redox-os/ion.git"
  "pkgutils|https://gitlab.redox-os.org/redox-os/pkgutils.git"
  "orbital|https://gitlab.redox-os.org/redox-os/orbital.git"
  "orbclient|https://gitlab.redox-os.org/redox-os/orbclient.git"
  "redoxer|https://gitlab.redox-os.org/redox-os/redoxer"
  "cosmic-edit|https://github.com/pop-os/cosmic-edit.git"
  "cosmic-files|https://github.com/pop-os/cosmic-files.git"
  "cosmic-monitor|https://github.com/pop-os/cosmic-monitor.git"
  "cosmic-reader|https://github.com/pop-os/cosmic-reader.git"
  "cosmic-settings|https://github.com/pop-os/cosmic-settings.git"
  "cosmic-store|https://github.com/pop-os/cosmic-store.git"
  "cosmic-term|https://github.com/pop-os/cosmic-term.git"
  "cosmic-text|https://github.com/pop-os/cosmic-text.git"
)

mkdir -p "$TMP/checkouts" "$ROOT/src"
for entry in "${components[@]}"; do
    name="${entry%%|*}"
    url="${entry#*|}"
    checkout="$TMP/checkouts/$name"
    destination="$ROOT/src/$name"

    echo "==> Cloning $name from $url"
    git clone --depth 1 --recurse-submodules "$url" "$checkout"
    commit="$(git -C "$checkout" rev-parse HEAD)"

    rm -rf "$destination"
    mkdir -p "$destination"
    rsync -a --delete --exclude='.git' "$checkout/" "$destination/"
    printf '%s\t%s\t%s\n' "$name" "$url" "$commit" >> "$LOCK"
done

cp "$LOCK" "$ROOT/src/UPSTREAMS.lock"
echo "Imported ${#components[@]} source trees under src/."
echo "This vendors the listed repositories only; recipe migration and full dependency coverage are separate required steps."
